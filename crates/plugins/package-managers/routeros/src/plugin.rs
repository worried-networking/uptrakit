    use super::*;
    use crate::config::RouterOsConfig;

    // ── mock executor ─────────────────────────────────────────────────────────

    struct MockExec {
        resource_output: String,
        package_update_output: String,
    }

    impl MockExec {
        fn new(
            resource_output: impl Into<String>,
            package_update_output: impl Into<String>,
        ) -> Arc<Self> {
            Arc::new(Self {
                resource_output: resource_output.into(),
                package_update_output: package_update_output.into(),
            })
        }
    }

    #[async_trait::async_trait]
    impl RouterOsExecutor for MockExec {
        async fn resource_print(&self) -> std::result::Result<String, PluginError> {
            Ok(self.resource_output.clone())
        }

        async fn routerboard_print(&self) -> std::result::Result<String, PluginError> {
            Ok(String::new())
        }

        async fn license_print(&self) -> std::result::Result<String, PluginError> {
            Ok(String::new())
        }

        async fn check_for_updates(&self) -> std::result::Result<(), PluginError> {
            Ok(())
        }

        async fn package_update_print(&self) -> std::result::Result<String, PluginError> {
            Ok(self.package_update_output.clone())
        }

        async fn package_install(&self) -> std::result::Result<(), PluginError> {
            Ok(())
        }

        async fn package_download(&self) -> std::result::Result<(), PluginError> {
            Ok(())
        }
    }

    // ── helpers ───────────────────────────────────────────────────────────────

    fn routeros_caps() -> HostCapabilities {
        HostCapabilities {
            os_family: Some(OsFamily::RouterOs),
            features: [host_features::ROUTER_OS_CLI].iter().cloned().collect(),
            ..Default::default()
        }
    }

    fn make_plugin(
        resource_output: &str,
        package_update_output: &str,
        reboot: bool,
        allow_reboot: bool,
    ) -> RouterOsPlugin {
        let exec = MockExec::new(resource_output, package_update_output);
        let runtime = construct_routeros_host_runtime(exec, routeros_caps(), allow_reboot);
        let config = RouterOsConfig {
            channel: None,
            reboot,
        };
        RouterOsPlugin::new(config, runtime).expect("plugin construction should succeed")
    }

    // ── construction ─────────────────────────────────────────────────────────

    #[test]
    fn plugin_creation_succeeds_with_valid_config() {
        let exec = MockExec::new("", "");
        let runtime = construct_routeros_host_runtime(exec, routeros_caps(), false);
        let config = RouterOsConfig {
            channel: Some("stable".to_string()),
            reboot: false,
        };
        assert!(RouterOsPlugin::new(config, runtime).is_ok());
    }

    #[test]
    fn plugin_creation_rejects_invalid_channel() {
        let exec = MockExec::new("", "");
        let runtime = construct_routeros_host_runtime(exec, routeros_caps(), false);
        let config = RouterOsConfig {
            channel: Some("canary".to_string()),
            reboot: false,
        };
        assert!(RouterOsPlugin::new(config, runtime).is_err());
    }

