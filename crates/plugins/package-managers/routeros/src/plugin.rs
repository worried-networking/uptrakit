// ── Discoverer ────────────────────────────────────────────────────────────────

#[async_trait]
impl Discoverer for RouterOsPlugin {
    /// Block cross-runtime invocation explicitly.
    ///
    /// The static `host_requirements` gate at the agent dispatch loop
    /// filters non-ROS hosts before discovery runs in normal operation, but
    /// falls through to this probe on legacy agents that haven't reported
    /// `os_family`. Without this override, `discover_software()` would run,
    /// the `ros_runtime()` downcast would fail, and the dispatch loop would
    /// emit a `tracing::warn!("discovery failed")` per such host per cycle.
    /// Returning `Incompatible` keeps the log path clean and the result
    /// an explicit empty.
    async fn detect_host_compatibility(&self) -> Result<HostCompatibility> {
        if self.ros_runtime().is_err() {
            return Ok(HostCompatibility::Incompatible(
                "RouterOS plugin requires a RouterOsHostRuntime".to_string(),
            ));
        }
        Ok(HostCompatibility::Compatible)
    }

    /// Self-report the RouterOS install as a single featured software item.
    ///
    /// Reuses `RouterOsExecutor::resource_print()` + the
    /// `parse_resource_version_with_display` parser. Returns `Ok(vec![])`
    /// when the version cannot be parsed (matches the trait contract:
    /// omit items with unknown versions).
    ///
    /// One `DiscoveryTarget` carrying all three roles back to this plugin —
    /// the controller's `process_targets_discovery` honors the
    /// package-manager branch and binds the roles to the host without
    /// auto-creating a `plugin_configs` row.
    #[tracing::instrument(skip_all)]
    async fn discover_software(&self) -> Result<Vec<DiscoveredSoftware>> {
        let ros_rt = self
            .ros_runtime()
            .map_err(|e| e.context_to::<PluginError>())?;

        let output = ros_rt
            .routeros_executor()
            .resource_print()
            .await
            .map_err(|e| report!(e))?;

        let Some((version, display)) = parse_resource_version_with_display(&output) else {
            tracing::debug!(
                "routeros discovery: `version` field absent from /system resource print output; \
                 omitting RouterOS software item"
            );
            return Ok(vec![]);
        };

        // Auto-fill `channel` from the parsed `(stable)` / `(long-term)` /
        // `(testing)` suffix when present, so the host's plugin config
        // matches the router's actual channel without operator action.
        // `reboot: false` by default — discovery is non-destructive; the
        // operator opts into auto-reboot via the form. Combined with the
        // runtime's `allow_reboot` policy gate, freshly-discovered routers
        // default to download-only behavior.
        let channel = RouterOsChannel::from_resource_suffix(&display);
        let plugin_config = serde_json::to_value(RouterOsConfig {
            channel,
            reboot: false,
        })
        .map_err(|e| {
            report!(PluginError::PluginInternal(format!(
                "failed to serialize discovery target plugin_config: {e}"
            )))
        })?;

        let target = DiscoveryTarget {
            plugin_type: plugin_ids::PACKAGE_MANAGER_ROUTEROS.clone(),
            // Package-manager plugins use type_settings, so the controller's
            // `is_package_manager_plugin` branch skips `plugin_configs`
            // find-or-create. The JSON still flows through to
            // `host_software_item_plugin.config` for default per-host
            // behavior.
            plugin_config,
            plugin_config_name: ROUTEROS_DISPLAY_NAME.to_string(),
            roles: vec![
                PluginRole::DetectVersion,
                PluginRole::FetchReleases,
                PluginRole::ExecuteUpdate,
            ],
            package_identifier: None,
            config_override: None,
            execution_site: None,
        };

        Ok(vec![DiscoveredSoftware {
            package_identifier: ROUTEROS_PACKAGE_IDENTIFIER.to_string(),
            name: ROUTEROS_DISPLAY_NAME.to_string(),
            installed_version: version,
            targets: vec![target],
            extra: None,
            qualifier: None,
            plugin_package_identifier: None,
            featured: true,
            installed_display_version: Some(display),
        }])
    }
}

// ── VersionDetector ───────────────────────────────────────────────────────────

#[async_trait]
impl VersionDetector for RouterOsPlugin {
    /// Detect the installed RouterOS version via `/system resource print`.
    ///
    /// Returns `None` when the `version` field is absent from the output (not
    /// a normal case on a healthy router, but handled defensively).
    async fn detect_installed_version(&self, _package_identifier: &str) -> Result<Option<Version>> {
        let ros_rt = self
            .ros_runtime()
            .map_err(|e| e.context_to::<PluginError>())?;

        let output = ros_rt
            .routeros_executor()
            .resource_print()
            .await
            .map_err(|e| report!(e))?;

        let version = parse_resource_version(&output).map(Version::new);
        Ok(version)
    }
}

// ── ReleaseFetcher ────────────────────────────────────────────────────────────

#[async_trait]
impl ReleaseFetcher for RouterOsPlugin {
    /// Fetch the latest available RouterOS version via `/system package update print`.
    ///
    /// Returns an empty vec when no `latest-version` field is present in the
    /// output (e.g., the router has not yet checked for updates or is already
    /// up to date and the field is absent).
    async fn fetch_releases(&self, _package_identifier: &str) -> Result<Vec<UpstreamRelease>> {
        let ros_rt = self
            .ros_runtime()
            .map_err(|e| e.context_to::<PluginError>())?;

        let output = ros_rt
            .routeros_executor()
            .package_update_print()
            .await
            .map_err(|e| report!(e))?;

        let Some(latest) = parse_latest_version(&output) else {
            return Err(report!(RouterOsError::VersionUnavailable(
                "latest-version absent from package update print output; \
                 ensure the router has completed a check-for-updates cycle"
                    .to_string()
            ))
            .context_to::<PluginError>());
        };

        let version = Version::new(&latest);
        let release = UpstreamRelease::new(
            version,
            latest.clone(),
            false,
            format!("https://mikrotik.com/download/changelogs/{latest}"),
        );

        Ok(vec![release])
    }
}

// ── UpdateExecutor ────────────────────────────────────────────────────────────

#[async_trait]
impl UpdateExecutor for RouterOsPlugin {
    /// Execute a RouterOS update.
    ///
    /// - Triggers `check-for-updates` on the router.
    /// - Waits 10 seconds for the router to complete the background check.
    /// - Issues `package install` (download + reboot) when both `config.reboot`
    ///   and `runtime.allow_reboot` are true; otherwise `package download`.
    ///
    /// The `package_identifier` and `to_version` parameters are informational
    /// (RouterOS manages all packages as a unit); they are not used directly.
    async fn execute_update(
        &self,
        _package_identifier: &str,
        _to_version: &str,
        _release_info: Option<&uptrakit_plugin_infrastructure_core::types::ReleaseInfo>,
        output_tx: &UpdateOutputSender,
    ) -> Result<ExecuteUpdateResult> {
        let ros_rt = self
            .ros_runtime()
            .map_err(|e| e.context_to::<PluginError>())?;

        let allow_reboot = ros_rt.allow_reboot;
        let executor = RouterOsUpdateExecutor {
            exec: ros_rt.routeros_executor(),
            reboot: self.config.reboot,
            allow_reboot,
        };

        executor
            .run_update()
            .await
            .map_err(|e| e.context_to::<PluginError>())?;

        let action = if self.config.reboot && allow_reboot {
            "RouterOS update installed; router will reboot"
        } else {
            "RouterOS update downloaded; manual reboot required to apply"
        };

        // Send a summary line to the output stream (best effort).
        send_output(output_tx, action, OutputStreamType::Stdout).await;

        // When reboot is active, the router will restart — mark as resumable
        // so the controller transitions to AwaitingRestart instead of Completed.
        let resumable = self.config.reboot && allow_reboot;
        Ok(ExecuteUpdateResult::new(action, resumable))
    }
}

