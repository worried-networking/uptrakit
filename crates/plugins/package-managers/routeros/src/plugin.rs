/// Stable identifier for the synthesized RouterOS software item. Pinned
/// here so tests and runtime can't drift.
const ROUTEROS_PACKAGE_IDENTIFIER: &str = "routeros";

/// Display name for the synthesized RouterOS software item.
const ROUTEROS_DISPLAY_NAME: &str = "MikroTik RouterOS";

/// Plugin for MikroTik RouterOS package management.
///
/// Supports installed version detection (via `/system resource print`),
/// available release fetching (via `/system package update print`), and
/// update execution (download-only or download+reboot based on config/policy).
///
/// **Runtime requirement:** the host runtime must be [`RouterOsHostRuntime`].
/// Any other runtime type causes role methods to return an error.
pub struct RouterOsPlugin {
    config: RouterOsConfig,
    runtime: Arc<dyn HostRuntime>,
}

impl RouterOsPlugin {
    /// Create a new RouterOS plugin, validating the config at construction time.
    pub fn new(
        config: RouterOsConfig,
        runtime: Arc<dyn HostRuntime>,
    ) -> std::result::Result<Self, PluginConfigValidationError> {
        use uptrakit_plugin_infrastructure_core::PluginConfig as _;
        config.validate()?;
        Ok(Self { config, runtime })
    }

    /// Downcast the host runtime to [`RouterOsHostRuntime`].
    ///
    /// Returns an error when the plugin is used with an incompatible runtime.
    fn ros_runtime(&self) -> std::result::Result<&RouterOsHostRuntime, Report<RouterOsError>> {
        self.runtime
            .as_any()
            .downcast_ref::<RouterOsHostRuntime>()
            .ok_or_else(|| {
                report!(RouterOsError::SshExec(
                    "RouterOsPlugin requires RouterOsHostRuntime; downcast failed".to_string()
                ))
            })
    }
}

