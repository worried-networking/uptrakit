    // ── detect_installed_version ──────────────────────────────────────────────

    #[tokio::test]
    async fn detect_installed_version_parses_output() {
        let plugin = make_plugin(
            "                   version: 7.14.2 (stable)\n     uptime: 3d\n",
            "",
            false,
            false,
        );
        let version = plugin
            .detect_installed_version("routeros")
            .await
            .expect("should succeed");
        assert_eq!(version.map(|v| v.to_string()), Some("7.14.2".to_string()));
    }

    #[tokio::test]
    async fn detect_installed_version_returns_none_when_absent() {
        let plugin = make_plugin("     uptime: 3d\n", "", false, false);
        let version = plugin
            .detect_installed_version("routeros")
            .await
            .expect("should succeed");
        assert!(version.is_none());
    }

    // ── fetch_releases ────────────────────────────────────────────────────────

    #[tokio::test]
    async fn fetch_releases_returns_latest_version() {
        let plugin = make_plugin(
            "",
            "  channel: stable\n  installed-version: 7.14\n  latest-version: 7.15\n",
            false,
            false,
        );
        let releases = plugin
            .fetch_releases("routeros")
            .await
            .expect("should succeed");
        assert_eq!(releases.len(), 1);
        assert_eq!(releases[0].version.to_string(), "7.15");
    }

    #[tokio::test]
    async fn fetch_releases_returns_err_when_no_latest() {
        let plugin = make_plugin(
            "",
            "  channel: stable\n  installed-version: 7.14\n",
            false,
            false,
        );
        let result = plugin.fetch_releases("routeros").await;
        let err = result.unwrap_err();
        assert!(
            err.to_string().contains("latest-version absent")
                || format!("{err:?}").contains("VersionUnavailable"),
            "expected VersionUnavailable error, got: {err}"
        );
    }

    // ── ros_runtime downcast failure ──────────────────────────────────────────

    #[tokio::test]
    async fn detect_installed_version_fails_with_wrong_runtime() {
        use uptrakit_plugin_infrastructure_core::{
            HostCapabilities, LocalCommandExecutor, StandardHostRuntime,
        };
        let executor = Arc::new(LocalCommandExecutor);
        let caps = HostCapabilities::default();
        let runtime = Arc::new(StandardHostRuntime::new(executor, caps));
        let config = RouterOsConfig::default();
        // Bypass the PluginConfig::validate step — use config that passes validation.
        // We need to construct via the internal path since ::new validates config,
        // but config is valid, so just use a plain struct construction workaround.
        let plugin = RouterOsPlugin {
            config,
            runtime: runtime as Arc<dyn HostRuntime>,
        };
        let result = plugin.detect_installed_version("routeros").await;
        assert!(result.is_err());
    }
